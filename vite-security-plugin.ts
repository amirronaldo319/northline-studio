import { createHash } from 'node:crypto'
import { readFileSync } from 'node:fs'
import path from 'node:path'
import type { Plugin } from 'vite'

interface CspOptions {
  /** `sha256-…` values for inline scripts the page needs. */
  scriptHashes: readonly string[]
  /** Origins the page may send requests to besides itself (e.g. the form service). */
  connectOrigins: readonly string[]
  /** Origins scripts may load from besides the page itself (e.g. an analytics beacon). */
  scriptOrigins?: readonly string[]
  /** A meta tag cannot carry `frame-ancestors`; leave it out there so browsers do not warn. */
  forMeta?: boolean
}

/** Returns the origin of a URL, or null when it is blank or not a valid URL. */
export function originOf(value: string): string | null {
  try {
    return new URL(value).origin
  } catch {
    return null
  }
}

/** Content-Security-Policy for this site: its own files only, plus explicitly listed origins and hashed scripts. */
export function buildCsp({ scriptHashes, connectOrigins, scriptOrigins = [], forMeta = false }: CspOptions): string {
  const directives = [
    "default-src 'self'",
    `script-src 'self'${scriptOrigins.map((origin) => ` ${origin}`).join('')}${scriptHashes.map((hash) => ` '${hash}'`).join('')}`,
    // React sets inline style attributes (for example the scroll reveal delays), so styles allow inline.
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data:",
    "font-src 'self'",
    `connect-src 'self'${connectOrigins.map((origin) => ` ${origin}`).join('')}`,
    "form-action 'self'",
    "base-uri 'self'",
    "object-src 'none'",
  ]
  if (!forMeta) directives.push("frame-ancestors 'none'")
  return directives.join('; ')
}

/** `sha256-…` hashes (base64) for every inline, executable script in the HTML. */
export function scriptHashes(html: string): string[] {
  const hashes: string[] = []
  for (const match of html.matchAll(/<script(?<attrs>[^>]*)>(?<body>[\s\S]*?)<\/script>/g)) {
    const attrs = match.groups?.attrs ?? ''
    if (/\bsrc=/.test(attrs) || /type=["']application\/ld\+json["']/.test(attrs)) continue
    const body = match.groups?.body ?? ''
    if (!body.trim()) continue
    hashes.push(`sha256-${createHash('sha256').update(body).digest('base64')}`)
  }
  return hashes
}

const OTHER_HEADERS = [
  'X-Content-Type-Options: nosniff',
  'Referrer-Policy: strict-origin-when-cross-origin',
  'Permissions-Policy: camera=(), microphone=(), geolocation=(), interest-cohort=()',
  'X-Frame-Options: DENY',
]

/**
 * Production builds only. Adds a CSP meta tag (the only place GitHub Pages lets a page set a policy) and writes
 * a `_headers` file with the same policy plus the headers a meta tag cannot carry, for Netlify and Cloudflare.
 */
export const ANALYTICS_SCRIPT_ORIGIN = 'https://static.cloudflareinsights.com'
export const ANALYTICS_CONNECT_ORIGIN = 'https://cloudflareinsights.com'

export function securityPlugin(options: { formEndpoint: string; analyticsToken?: string }): Plugin {
  const hasAnalytics = Boolean(options.analyticsToken)
  const connectOrigins = [originOf(options.formEndpoint), hasAnalytics ? ANALYTICS_CONNECT_ORIGIN : null].filter(
    (origin): origin is string => origin !== null,
  )
  const scriptOrigins = hasAnalytics ? [ANALYTICS_SCRIPT_ORIGIN] : []
  let hashes: string[] = []

  return {
    name: 'sitepilot-security',
    apply: 'build',
    // Hash the inline scripts of the source page up front, so `_headers` (written during bundling, before the
    // HTML is finalised) and the meta tag agree.
    configResolved(config) {
      hashes = scriptHashes(readFileSync(path.join(config.root, 'index.html'), 'utf8'))
    },
    transformIndexHtml: {
      order: 'post',
      handler(html) {
        hashes = [...new Set([...hashes, ...scriptHashes(html)])]
        const content = buildCsp({ scriptHashes: hashes, connectOrigins, scriptOrigins, forMeta: true })
        return [
          { tag: 'meta', attrs: { 'http-equiv': 'Content-Security-Policy', content }, injectTo: 'head-prepend' },
        ]
      },
    },
    generateBundle() {
      const csp = buildCsp({ scriptHashes: hashes, connectOrigins, scriptOrigins })
      const source = [
        '# Generated by vite-security-plugin.ts. Read by Netlify and Cloudflare Pages; GitHub Pages ignores it',
        '# and relies on the CSP meta tag in index.html.',
        '/*',
        `  Content-Security-Policy: ${csp}`,
        ...OTHER_HEADERS.map((line) => `  ${line}`),
        '',
        '/assets/*',
        '  Cache-Control: public, max-age=31536000, immutable',
        '',
      ].join('\n')
      this.emitFile({ type: 'asset', fileName: '_headers', source })
    },
  }
}
